// Generates the site's colour blocks from the app's own theme files so the two can't drift.
// Reads ../frontend/src/themes/<id>.css (shadcn HSL triplets) and writes:
//   app/themes.generated.css  — --color-fd-* overrides per [data-theme]
//   lib/themes.generated.ts   — id/label list for the picker
// Only the "Parallax set" is exposed on the site.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const themesDir = path.resolve(here, "../../frontend/src/themes");

const THEMES = [
  { id: "parallax", label: "Parallax" },
  { id: "elegance", label: "Elegance" },
  { id: "graphite", label: "Graphite" },
  { id: "rose", label: "Rose Quartz" },
  { id: "oled", label: "OLED" },
];
const DEFAULT_THEME = "parallax";

// Cross-check against the app registry so a renamed/removed theme fails loudly.
const registry = readFileSync(path.join(themesDir, "registry.ts"), "utf8");
for (const { id, label } of THEMES) {
  if (!registry.includes(`{ id: "${id}", label: "${label}", group: "Parallax" }`)) {
    throw new Error(`Theme "${id}" ("${label}") not found in the Parallax group of registry.ts`);
  }
}

function readVars(id) {
  const css = readFileSync(path.join(themesDir, `${id}.css`), "utf8");
  const vars = {};
  for (const m of css.matchAll(
    /^\s*--([a-z-]+):\s*(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%\s*;/gm,
  )) {
    vars[m[1]] = `${m[2]} ${m[3]}% ${m[4]}%`;
  }
  return vars;
}

const hsl = (vars, name) => {
  if (!vars[name]) throw new Error(`missing --${name}`);
  return `hsl(${vars[name]})`;
};

function block(selector, sidebarSelector, v) {
  return `${selector} {
  color-scheme: dark;
  --color-fd-background: ${hsl(v, "background")};
  --color-fd-foreground: ${hsl(v, "foreground")};
  --color-fd-muted: ${hsl(v, "muted")};
  --color-fd-muted-foreground: ${hsl(v, "muted-foreground")};
  --color-fd-popover: ${hsl(v, "popover")};
  --color-fd-popover-foreground: ${hsl(v, "popover-foreground")};
  --color-fd-card: ${hsl(v, "card")};
  --color-fd-card-foreground: ${hsl(v, "card-foreground")};
  --color-fd-border: ${hsl(v, "border")};
  --color-fd-primary: ${hsl(v, "primary")};
  --color-fd-primary-foreground: ${hsl(v, "primary-foreground")};
  --color-fd-secondary: ${hsl(v, "secondary")};
  --color-fd-secondary-foreground: ${hsl(v, "secondary-foreground")};
  --color-fd-accent: ${hsl(v, "accent")};
  --color-fd-accent-foreground: ${hsl(v, "accent-foreground")};
  --color-fd-ring: ${hsl(v, "ring")};
}
/* fumadocs-ui's \`.dark #nd-sidebar { ... }\` outranks the block above, so match it. */
${sidebarSelector} #nd-sidebar {
  --color-fd-card: ${hsl(v, "sidebar")};
  --color-fd-muted: ${hsl(v, "muted")};
  --color-fd-secondary: ${hsl(v, "secondary")};
  --color-fd-muted-foreground: ${hsl(v, "muted-foreground")};
  --color-fd-border: ${hsl(v, "sidebar-border")};
}
`;
}

let css = `/* GENERATED by scripts/sync-themes.mjs from ../frontend/src/themes — do not edit. */\n`;
css += `/* Plain rules, not \`@theme\`: Tailwind v4 hoists \`@theme\` above fumadocs-ui's own \`.dark\` block and loses the cascade tie. */\n\n`;
const def = readVars(DEFAULT_THEME);
css += block(`:root`, `:root`, def) + "\n";
for (const { id } of THEMES) {
  const sel = `:root[data-theme="${id}"]`;
  css += block(sel, sel, readVars(id)) + "\n";
}
writeFileSync(path.resolve(here, "../app/themes.generated.css"), css);

const ts = `// GENERATED by scripts/sync-themes.mjs — do not edit.
export const THEMES = ${JSON.stringify(THEMES, null, 2)} as const;
export const DEFAULT_THEME = ${JSON.stringify(DEFAULT_THEME)};
export type ThemeId = (typeof THEMES)[number]["id"];
`;
writeFileSync(path.resolve(here, "../lib/themes.generated.ts"), ts);
console.log(`sync-themes: wrote ${THEMES.length} themes`);
